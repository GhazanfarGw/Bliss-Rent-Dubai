// Regenerates src/features/booking/worldMapPath.ts — the real-world SVG
// path data behind the homepage's "coverage map" (LocationsPreviewSection).
// Standalone/one-off (`npm run map:path`), not part of the normal build:
// the projection rarely changes, so the output is committed as a plain
// static export rather than re-derived on every build.
//
// Source data: the `world-atlas` package's 110m-resolution Natural Earth
// country topology (low-detail — appropriate for a decorative background,
// not a precision basemap). Every country is merged into one landmass
// silhouette (no internal borders) via `topojson-client`, projected with
// `d3-geo`'s equirectangular projection.
//
// The whole world is drawn (so the map fills the panel edge to edge), but
// the projection is ROTATED to put CENTER_LON (the Gulf's longitude, more
// or less) in the middle of the image instead of lon 0 — the layout
// (coverageMapLayout.ts) covers the panel with this image and centers the
// UAE cluster, so on a narrow phone-width panel the visible crop lands on
// Africa/Europe/the Middle East/India instead of the mid-Atlantic. The
// seam (the map's left/right edge) therefore sits at CENTER_LON ± 180,
// out in the Pacific.
//
// To change the framing, edit the constants below and re-run this script.
import { writeFileSync, readFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, resolve } from 'node:path'
import { feature, merge } from 'topojson-client'
import { geoEquirectangular, geoPath, geoBounds, geoArea } from 'd3-geo'

const __dirname = dirname(fileURLToPath(import.meta.url))
const outPath = resolve(__dirname, '../src/features/booking/worldMapPath.ts')

/** Longitude placed at the horizontal center of the image. */
const CENTER_LON = 30
/** Latitude band kept: just above Antarctica's coast down to the Arctic islands. */
const LAT_MIN = -58
const LAT_MAX = 84
/** Output width in SVG user units; height follows from the lat band so the map keeps true equirectangular proportions. */
const WIDTH = 200
/** Polygons smaller than this (in steradians, ~12,000 km2) are dropped — specks on a faint watermark, but they cost path bytes. */
const MIN_AREA_SR = 3e-4

const scale = WIDTH / (2 * Math.PI)
const degToRad = Math.PI / 180
const HEIGHT = Math.round((LAT_MAX - LAT_MIN) * degToRad * scale * 100) / 100
const translateY = LAT_MAX * degToRad * scale

const topo = JSON.parse(readFileSync(resolve(__dirname, '../node_modules/world-atlas/countries-110m.json'), 'utf8'))

// Antarctica (and anything else wholly outside the latitude band) is
// dropped before merging — it would only project below the viewBox.
const countryFeatures = feature(topo, topo.objects.countries).features
const keptIds = new Set(
  countryFeatures
    .filter((f) => {
      const [[, latMin], [, latMax]] = geoBounds(f)
      return latMax >= LAT_MIN && latMin <= LAT_MAX
    })
    .map((f) => f.id),
)
const merged = merge(
  topo,
  topo.objects.countries.geometries.filter((g) => keptIds.has(g.id)),
)

const polygons = merged.coordinates.map((coordinates) => ({ type: 'Polygon', coordinates }))
const bigEnough = polygons.filter((polygon) => geoArea(polygon) >= MIN_AREA_SR)
const land = { type: 'MultiPolygon', coordinates: bigEnough.map((p) => p.coordinates) }

const projection = geoEquirectangular()
  .rotate([-CENTER_LON, 0])
  .scale(scale)
  .translate([WIDTH / 2, translateY])
  .clipExtent([
    [0, 0],
    [WIDTH, HEIGHT],
  ])

const rawPath = geoPath(projection)(land)
// Round every coordinate to 1 decimal — 0.1 of a 200-unit-wide image is
// well under a pixel at any size this renders at, and it keeps the
// emitted string (shipped in the JS bundle) as small as it can be.
const path = rawPath.replace(/-?\d+\.\d+/g, (n) => String(Math.round(parseFloat(n) * 10) / 10))

const header = `/**
 * Real-world SVG path data for the homepage "coverage map" backdrop
 * (LocationsPreviewSection) — the WHOLE world's landmass merged into one
 * silhouette (no internal borders), generated by
 * scripts/generate-coverage-map-path.mjs (\`npm run map:path\`) from the
 * world-atlas package's 110m-resolution Natural Earth topology via
 * topojson-client + d3-geo's geoEquirectangular(), rotated so lon
 * ${CENTER_LON} is the image's center, lat ${LAT_MIN}..${LAT_MAX}, tiny islands dropped, coordinates
 * rounded to 1 decimal. Committed as a static export, not regenerated at
 * build/runtime — edit the constants in the generator script and re-run
 * it if the framing ever needs to change.
 *
 * Render it in an SVG whose viewBox is WORLD_MAP_VIEW_BOX, sized to a box
 * with that same aspect ratio (see coverageMapLayout.ts, which "covers"
 * the panel with that box) so the continents keep true proportions.
 */
export const WORLD_MAP_VIEW_BOX = '0 0 ${WIDTH} ${HEIGHT}'

/** The projection's framing, so callers can place a real lon/lat on the same image (see coverageMapLayout.ts). */
export const WORLD_MAP_PROJECTION = { centerLon: ${CENTER_LON}, latMin: ${LAT_MIN}, latMax: ${LAT_MAX} } as const

export const WORLD_MAP_PATH = ${JSON.stringify(path)}
`

writeFileSync(outPath, header)
console.log(
  `Wrote ${outPath}: ${path.length.toLocaleString()} chars of path data, viewBox 0 0 ${WIDTH} ${HEIGHT}, ` +
    `${bigEnough.length}/${polygons.length} landmasses kept (${keptIds.size} countries)`,
)
